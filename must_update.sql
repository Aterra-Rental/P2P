-- Permanent service-fee ledger for both completed and
-- cancelled funded deals.
CREATE TABLE IF NOT EXISTS
    public.platform_fee_transactions (
        platform_fee_transaction_id integer
            GENERATED BY DEFAULT AS IDENTITY,

        room_id integer,
        room_code character varying(10) NOT NULL,
        -- Present only for completed deals.
        transaction_id integer,
        -- User economically charged for the fee.
        charged_user_id integer NOT NULL,
        -- The payer selected during fee negotiation.
        agreed_fee_payer character varying(6) NOT NULL,
        event_type character varying(20) NOT NULL,
        payment_method character varying(20) NOT NULL,
        fee_amount numeric(12,2) NOT NULL,
        currency character varying(3)
            DEFAULT 'USD' NOT NULL,
        reference_key character varying(150) NOT NULL,
        created_at timestamp with time zone
            DEFAULT CURRENT_TIMESTAMP NOT NULL,
        CONSTRAINT platform_fee_transactions_pkey
            PRIMARY KEY (
                platform_fee_transaction_id
            ),
        CONSTRAINT platform_fee_reference_unique
            UNIQUE (reference_key),
        CONSTRAINT platform_fee_room_fkey
            FOREIGN KEY (room_id)
            REFERENCES public.room(room_id)
            ON DELETE SET NULL,

        CONSTRAINT platform_fee_history_fkey
            FOREIGN KEY (transaction_id)
            REFERENCES public.transactions_history(
                transaction_id
            )
            ON DELETE SET NULL,

        CONSTRAINT platform_fee_user_fkey
            FOREIGN KEY (charged_user_id)
            REFERENCES public.user_login(user_id)
            ON DELETE RESTRICT,

        CONSTRAINT platform_fee_payer_check
            CHECK (
                agreed_fee_payer IN (
                    'buyer',
                    'seller'
                )
            ),

        CONSTRAINT platform_fee_event_check
            CHECK (
                event_type IN (
                    'Completed',
                    'Cancelled'
                )
            ),

        CONSTRAINT platform_fee_method_check
            CHECK (
                payment_method IN (
                    'Wallet',
                    'KHQR'
                )
            ),

        CONSTRAINT platform_fee_amount_positive
            CHECK (fee_amount > 0),

        CONSTRAINT platform_fee_currency_check
            CHECK (currency = 'USD')
            );


