CREATE TABLE IF NOT EXISTS public.deal_fee_agreement (
    room_id integer NOT NULL,
    fee_payer character varying(6),
    proposed_by integer,
    fee_amount numeric(12,2) NOT NULL,
    buyer_deposit numeric(12,2),
    seller_receive numeric(12,2),
    buyer_confirmed boolean DEFAULT false NOT NULL,
    seller_confirmed boolean DEFAULT false NOT NULL,
    updated_at timestamp without time zone
        DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT deal_fee_agreement_pkey
        PRIMARY KEY (room_id),
    CONSTRAINT deal_fee_payer_check
        CHECK (
            fee_payer IS NULL
            OR fee_payer::text = ANY (
                ARRAY['buyer', 'seller']::text[]
            )
        )
);
CREATE TABLE IF NOT EXISTS public.deal_payment_attempt (
    payment_attempt_id integer
        GENERATED BY DEFAULT AS IDENTITY,
    room_id integer NOT NULL,
    khqr_md5 character varying(100) NOT NULL,
    qr_payload text NOT NULL,
    expected_amount numeric(12,2) NOT NULL,
    currency character varying(3)
        DEFAULT 'USD'::character varying NOT NULL,
    receiver_account character varying(255) NOT NULL,
    status character varying(20)
        DEFAULT 'Generated'::character varying NOT NULL,
    expires_at timestamp with time zone NOT NULL,
    verification_attempts integer DEFAULT 0 NOT NULL,
    last_verification_at timestamp with time zone,
    verified_at timestamp with time zone,
    created_at timestamp with time zone
        DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT deal_payment_attempt_pkey
        PRIMARY KEY (payment_attempt_id),

    CONSTRAINT deal_payment_attempt_room_fkey
        FOREIGN KEY (room_id)
        REFERENCES public.room(room_id)
        ON DELETE CASCADE,

    CONSTRAINT deal_payment_attempt_md5_unique
        UNIQUE (khqr_md5),

    CONSTRAINT deal_payment_attempt_amount_positive
        CHECK (expected_amount > 0),

    CONSTRAINT deal_payment_attempt_attempts_nonnegative
        CHECK (verification_attempts >= 0),

    CONSTRAINT deal_payment_attempt_currency_check
    CHECK (currency = 'USD'),

    CONSTRAINT deal_payment_attempt_status_check
        CHECK (
            status::text = ANY (
                ARRAY[
                    'Generated',
                    'Verified',
                    'Expired',
                    'Failed'
                ]::text[]
            )
        )
);
