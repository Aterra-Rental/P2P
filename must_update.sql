-- Temporary mutual-cancellation agreement for a funded deal.
CREATE TABLE IF NOT EXISTS
    public.deal_cancellation_request (
        room_id integer NOT NULL,
        requested_by integer NOT NULL,
        rejected_by integer,

        reason text NOT NULL,

        buyer_confirmed boolean
            DEFAULT false NOT NULL,
        seller_confirmed boolean
            DEFAULT false NOT NULL,

        status character varying(20)
            DEFAULT 'Pending' NOT NULL,

        refund_amount numeric(12,2),
        retained_fee numeric(12,2),

        requested_at timestamp with time zone
            DEFAULT CURRENT_TIMESTAMP NOT NULL,
        updated_at timestamp with time zone
            DEFAULT CURRENT_TIMESTAMP NOT NULL,
        processed_at timestamp with time zone,

        CONSTRAINT deal_cancellation_request_pkey
            PRIMARY KEY (room_id),

        CONSTRAINT deal_cancellation_room_fkey
            FOREIGN KEY (room_id)
            REFERENCES public.room(room_id)
            ON DELETE CASCADE,

        CONSTRAINT deal_cancellation_requester_fkey
            FOREIGN KEY (requested_by)
            REFERENCES public.user_login(user_id)
            ON DELETE RESTRICT,

        CONSTRAINT deal_cancellation_rejected_by_fkey
            FOREIGN KEY (rejected_by)
            REFERENCES public.user_login(user_id)
            ON DELETE RESTRICT,

        CONSTRAINT deal_cancellation_status_check
            CHECK (
                status IN (
                    'Pending',
                    'Rejected',
                    'Processed'
                )
            ),

        CONSTRAINT deal_cancellation_reason_check
            CHECK (
                length(trim(reason)) >= 5
            ),

        CONSTRAINT deal_cancellation_amounts_check
            CHECK (
                (
                    refund_amount IS NULL
                    OR refund_amount >= 0
                )
                AND (
                    retained_fee IS NULL
                    OR retained_fee >= 0
                )
            )
    );
