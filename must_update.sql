-- Backfill platform fees from completed deals that
-- existed before platform_fee_transactions was added.
INSERT INTO public.platform_fee_transactions (
    room_id,
    room_code,
    transaction_id,
    charged_user_id,
    agreed_fee_payer,
    event_type,
    payment_method,
    fee_amount,
    currency,
    reference_key
)
SELECT
    th.room_id,
    th.room_code,
    th.transaction_id,
    CASE
        WHEN th.fee_payer = 'seller'
            THEN th.seller_id
        ELSE th.buyer_id
    END,
    COALESCE(
        th.fee_payer,
        'buyer'
    ),
    'Completed',
    CASE
        WHEN th.payment_provider = 'Wallet'
            THEN 'Wallet'
        ELSE 'KHQR'
    END,
    th.fee_amount,
    'USD',
    (
        'deal:'
        || th.room_code
        || ':completed_fee'
    )
FROM public.transactions_history th
WHERE th.transaction_status = 'Completed'
  AND th.room_code IS NOT NULL
  AND th.fee_amount > 0
ON CONFLICT (reference_key) DO NOTHING;
-- Persistent notifications belonging to individual users.
CREATE TABLE IF NOT EXISTS public.user_notifications (
    notification_id bigint
        GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    actor_user_id integer,
    notification_type character varying(40)
        NOT NULL,
    title character varying(255) NOT NULL,
    message text NOT NULL,
    room_id integer,
    room_code character varying(20),
    announcement_id integer,
    is_read boolean DEFAULT false NOT NULL,
    created_at timestamp without time zone
        DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT user_notifications_pkey
        PRIMARY KEY (notification_id),

    CONSTRAINT user_notifications_user_fkey
        FOREIGN KEY (user_id)
        REFERENCES public.user_login(user_id)
        ON DELETE CASCADE,

    CONSTRAINT user_notifications_actor_fkey
        FOREIGN KEY (actor_user_id)
        REFERENCES public.user_login(user_id)
        ON DELETE SET NULL,

    CONSTRAINT user_notifications_room_fkey
        FOREIGN KEY (room_id)
        REFERENCES public.room(room_id)
        ON DELETE SET NULL,

    CONSTRAINT user_notifications_announcement_fkey
        FOREIGN KEY (announcement_id)
        REFERENCES public.announcements(
            announcement_id
        )
        ON DELETE CASCADE,

    CONSTRAINT user_notifications_type_check
        CHECK (
            notification_type::text = ANY (
                ARRAY[
                    'Announcement',
                    'DealReminder',
                    'InvitationAccepted',
                    'InvitationRejected',
                    'CancellationRequested',
                    'CancellationRejected',
                    'DealCancelled'
                ]::text[]
            )
        ),

    CONSTRAINT user_notifications_title_not_blank
        CHECK (length(trim(title)) > 0),

    CONSTRAINT user_notifications_message_not_blank
        CHECK (length(trim(message)) > 0)
);

