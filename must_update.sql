-- P2P Deal schema synchronizer (PostgreSQL 18)
-- Creates missing tables and adds missing columns, constraints, sequences, and indexes.
-- Safe to run repeatedly on an existing database.
-- IMPORTANT: transactions_history is intentionally limited to Completed deals only.

