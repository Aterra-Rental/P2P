-- Give existing users a personal copy of every active
-- announcement created before this table existed.
INSERT INTO public.user_notifications (
    user_id,
    notification_type,
    title,
    message,
    announcement_id,
    is_read,
    created_at
)
SELECT
    login.user_id,
    'Announcement',
    announcement.title,
    announcement.message,
    announcement.announcement_id,
    false,
    announcement.created_at
FROM public.user_login login
CROSS JOIN public.announcements announcement
WHERE announcement.is_active = true
ON CONFLICT (
    announcement_id,
    user_id
)
WHERE announcement_id IS NOT NULL
DO NOTHING;

