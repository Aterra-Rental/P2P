-- Temporary escrow state for an active deal.
CREATE TABLE IF NOT EXISTS public.deal_escrow (
    room_id integer NOT NULL,
    room_code character varying(10) NOT NULL,

    buyer_id integer NOT NULL,
    seller_id integer NOT NULL,

    payment_method character varying(10) NOT NULL,
    payment_attempt_id integer,

    held_amount numeric(12,2) NOT NULL,
    fee_amount numeric(12,2) DEFAULT 0.00 NOT NULL,
    seller_receive numeric(12,2) NOT NULL,

    status character varying(20)
        DEFAULT 'AwaitingPayment' NOT NULL,

    created_at timestamp with time zone
        DEFAULT CURRENT_TIMESTAMP NOT NULL,
    held_at timestamp with time zone,
    released_at timestamp with time zone,
    refunded_at timestamp with time zone,
    updated_at timestamp with time zone
        DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT deal_escrow_pkey
        PRIMARY KEY (room_id),

    CONSTRAINT deal_escrow_room_code_unique
        UNIQUE (room_code),

    CONSTRAINT deal_escrow_room_fkey
        FOREIGN KEY (room_id)
        REFERENCES public.room(room_id)
        ON DELETE RESTRICT,

    CONSTRAINT deal_escrow_buyer_fkey
        FOREIGN KEY (buyer_id)
        REFERENCES public.user_login(user_id)
        ON DELETE RESTRICT,

    CONSTRAINT deal_escrow_seller_fkey
        FOREIGN KEY (seller_id)
        REFERENCES public.user_login(user_id)
        ON DELETE RESTRICT,

    CONSTRAINT deal_escrow_payment_attempt_fkey
        FOREIGN KEY (payment_attempt_id)
        REFERENCES public.deal_payment_attempt(
            payment_attempt_id
        )
        ON DELETE SET NULL,

    CONSTRAINT deal_escrow_payment_method_check
        CHECK (
            payment_method IN ('Wallet', 'KHQR')
        ),

    CONSTRAINT deal_escrow_status_check
        CHECK (
            status IN (
                'AwaitingPayment',
                'Held',
                'Disputed',
                'Released',
                'Refunded'
            )
        ),

    CONSTRAINT deal_escrow_amounts_check
        CHECK (
            held_amount > 0
            AND fee_amount >= 0
            AND seller_receive >= 0
            AND seller_receive <= held_amount
        )
);


-- Permanent history of every wallet balance movement.
CREATE TABLE IF NOT EXISTS public.wallet_transactions (
    wallet_transaction_id integer
        GENERATED BY DEFAULT AS IDENTITY,

    user_id integer NOT NULL,

    -- room_id can become NULL after temporary room cleanup.
    room_id integer,
    room_code character varying(10),

    payment_attempt_id integer,

    transaction_type character varying(30) NOT NULL,
    amount numeric(12,2) NOT NULL,

    available_change numeric(12,2)
        DEFAULT 0.00 NOT NULL,
    pending_change numeric(12,2)
        DEFAULT 0.00 NOT NULL,

    available_balance_after numeric(12,2) NOT NULL,
    pending_balance_after numeric(12,2) NOT NULL,

    -- Example: deal:QY9UZR:wallet_hold
    reference_key character varying(150) NOT NULL,

    description text,
    created_at timestamp with time zone
        DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT wallet_transactions_pkey
        PRIMARY KEY (wallet_transaction_id),

    CONSTRAINT wallet_transactions_reference_unique
        UNIQUE (reference_key),

    CONSTRAINT wallet_transactions_user_fkey
        FOREIGN KEY (user_id)
        REFERENCES public.user_login(user_id)
        ON DELETE RESTRICT,

    CONSTRAINT wallet_transactions_room_fkey
        FOREIGN KEY (room_id)
        REFERENCES public.room(room_id)
        ON DELETE SET NULL,

    CONSTRAINT wallet_transactions_payment_attempt_fkey
        FOREIGN KEY (payment_attempt_id)
        REFERENCES public.deal_payment_attempt(
            payment_attempt_id
        )
        ON DELETE SET NULL,

    CONSTRAINT wallet_transactions_type_check
        CHECK (
            transaction_type IN (
                'Deposit',
                'DealHold',
                'EscrowRelease',
                'Refund',
                'SellerCredit',
                'Withdrawal',
                'Fee'
            )
        ),

    CONSTRAINT wallet_transactions_amount_positive
        CHECK (amount > 0),

    CONSTRAINT wallet_transactions_changes_check
        CHECK (
            available_change <> 0
            OR pending_change <> 0
        ),

    CONSTRAINT wallet_transactions_balances_nonnegative
        CHECK (
            available_balance_after >= 0
            AND pending_balance_after >= 0
        )
);

